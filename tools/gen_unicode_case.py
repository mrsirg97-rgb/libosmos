"""src/text/unicode_case.h: each code point's place in o200k's two letter classes (Inkling-2's pre-tokenizer, the
GPT-4o expression): [\\p{Lu}\\p{Lt}\\p{Lm}\\p{Lo}\\p{M}] (bit 1, "upper") and [\\p{Ll}\\p{Lm}\\p{Lo}\\p{M}] (bit 2,
"lower") - Lm, Lo and the marks in both. from Python's unicodedata, its version checked against llama.cpp's table's
(unicode_data.h: 15.1). run: python3 tools/gen_unicode_case.py > src/text/unicode_case.h"""
import unicodedata

assert unicodedata.unidata_version == "15.1.0", unicodedata.unidata_version


def cls(c):
    cat = unicodedata.category(chr(c))
    if cat in ("Lu", "Lt"):
        return 1
    if cat == "Ll":
        return 2
    if cat in ("Lm", "Lo") or cat[0] == "M":
        return 3
    return 0


ranges = []
for c in range(0x110000):
    k = cls(c)
    if not ranges or ranges[-1][1] != k:
        ranges.append((c, k))
out = ["// generated by tools/gen_unicode_case.py from Python's unicodedata (Unicode 15.1, llama.cpp's) - do not edit",
       "// a code point's o200k letter classes: those of the last range starting at or before it", "#pragma once",
       "#include <stdint.h>", "", "enum { UC_CASE_UPPER = 1, UC_CASE_LOWER = 2 };", "",
       f"#define UC_CASE_RANGES {len(ranges)}", "static const uint32_t uc_case_start[UC_CASE_RANGES] = {"]
for i in range(0, len(ranges), 8):
    out.append("  " + ", ".join(f"0x{a:06X}" for a, _ in ranges[i:i + 8]) + ",")
out += ["};", "static const uint8_t uc_case_class[UC_CASE_RANGES] = {"]
for i in range(0, len(ranges), 24):
    out.append("  " + ", ".join(str(k) for _, k in ranges[i:i + 24]) + ",")
out.append("};")
print("\n".join(out))

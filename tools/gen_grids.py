"""kernels/quant_grids.h from gguf-py's own tables (llama.cpp, MIT): the IQ grids as gguf-py decodes them, so the
GPU's grids are the oracle's. run: PYTHONPATH=<llama.cpp>/gguf-py .oracle-venv/bin/python tools/gen_grids.py"""
import sys

import numpy as np
from gguf import quants as Q


def grid(cls):
    cls.init_grid()
    g = cls.grid.reshape(cls.grid_shape).astype(np.int8)  # IQ2: 0x08/0x19/0x2b; IQ1: -1/0/1
    assert g.shape[1] == 8
    return [int.from_bytes(row.tobytes(), "little") for row in g]


def table(name, ctype, vals, fmt, per_line):
    out = ["static __constant__ %s %s[%d] = {" % (ctype, name, len(vals))]
    for i in range(0, len(vals), per_line):
        out.append("  " + ", ".join(fmt % v for v in vals[i:i + per_line]) + ",")
    return out + ["};", ""]


def main():
    lines = ["// generated by tools/gen_grids.py from gguf-py's quants.py (llama.cpp, MIT); do not edit",
             "#pragma once", "#include <cstdint>", ""]
    lines += table("kIq2xxsGrid", "uint64_t", grid(Q.IQ2_XXS), "0x%016xull", 4)
    lines += table("kIq2xsGrid", "uint64_t", grid(Q.IQ2_XS), "0x%016xull", 4)
    lines += table("kIq1sGrid", "uint64_t", grid(Q.IQ1_S), "0x%016xull", 4)
    lines += table("kKsigns", "uint8_t", list(Q.IQ2_XXS.ksigns), "0x%02x", 16)
    lines += table("kIq4nlValues", "int8_t", list(Q.IQ4_NL.kvalues), "%d", 16)
    assert Q.IQ1_M.grid_hex == Q.IQ1_S.grid_hex and Q.IQ1_S.delta == np.float32(0.125)
    sys.stdout.write("\n".join(lines))


main()

"""src/text/unicode_data.h from llama.cpp's own table (src/unicode-data.cpp, MIT: generated there from the Unicode
data), so a code point's categories are the ones its tokenizer split by. run: python3 tools/gen_unicode.py
<llama.cpp>/src/unicode-data.cpp > src/text/unicode_data.h"""
import re
import sys


def section(src, name):
    i = src.index(name)
    return src[src.index("{", i) + 1:src.index("};", i)]


def main():
    src = open(sys.argv[1], encoding="utf-8").read()
    ranges = [(int(a, 16), int(b, 16)) for a, b in
              re.findall(r"\{0x([0-9A-Fa-f]+),\s*0x([0-9A-Fa-f]+)\}", section(src, "unicode_ranges_flags"))]
    space = [int(a, 16) for a in re.findall(r"0x([0-9A-Fa-f]+)", section(src, "unicode_set_whitespace"))]
    assert ranges[0][0] == 0 and ranges == sorted(ranges) and space == sorted(space)
    out = ["// generated by tools/gen_unicode.py from llama.cpp's src/unicode-data.cpp (MIT) - do not edit",
           "// a code point's flags: those of the last range starting at or before it (llama.cpp's unicode_cpt_flags)",
           "#pragma once", "#include <stdint.h>", "",
           "enum { UC_NUMBER = 0x0002, UC_LETTER = 0x0004, UC_SEPARATOR = 0x0008, UC_MARK = 0x0010,",
           "       UC_PUNCT = 0x0020, UC_SYMBOL = 0x0040, UC_CONTROL = 0x0080, UC_CATEGORIES = 0x00FF };", "",
           f"#define UC_RANGES {len(ranges)}",
           "static const uint32_t uc_range_start[UC_RANGES] = {"]
    for i in range(0, len(ranges), 8):
        out.append("  " + ", ".join(f"0x{a:06X}" for a, _ in ranges[i:i + 8]) + ",")
    out += ["};", "static const uint16_t uc_range_flags[UC_RANGES] = {"]
    for i in range(0, len(ranges), 12):
        out.append("  " + ", ".join(f"0x{b:04X}" for _, b in ranges[i:i + 12]) + ",")
    out += ["};", "", f"#define UC_SPACES {len(space)}", "static const uint32_t uc_space[UC_SPACES] = {"]
    for i in range(0, len(space), 8):
        out.append("  " + ", ".join(f"0x{a:06X}" for a in space[i:i + 8]) + ",")
    out += ["};", ""]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
